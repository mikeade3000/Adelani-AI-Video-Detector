// Builds the Cloudflare version from the shared sources (run by `npm run deploy` and deploy.cmd):
//   ../apps-script/Code.gs            → src/app.generated.js  (the same exam backend, given the Cloudflare services)
//   ../*.html, ../assets, ../samples  → public/               (the website; config.js points at /api)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const cf = path.resolve(here, '..'), root = path.resolve(cf, '..');

// Apps Script services the backend uses; the shims (src/shims.js) provide each one.
const SERVICES = ['SpreadsheetApp', 'CacheService', 'PropertiesService', 'LockService', 'DriveApp', 'Utilities',
  'ContentService', 'HtmlService', 'Session', 'Logger', 'MailApp'];
// Functions the Cloudflare engine replaces with faster SQL versions (see createShims().hooks).
const HOOKS = ['activityFor_', 'activityRecent_', 'recordingsFor_', 'recordingOwner_', 'cacheGetLarge_', 'mailStatus_', 'deliverMail_', 'removeRecordings_'];

const code = fs.readFileSync(path.join(root, 'apps-script', 'Code.gs'), 'utf8');
const names = [...code.matchAll(/^(?:async )?function ([A-Za-z_$][\w$]*)\s*\(/gm)].map(m => m[1]);
for (const h of HOOKS) if (!names.includes(h)) throw new Error('Code.gs has no function ' + h + ' (listed in HOOKS)');
const indent = s => s.split('\n').map(l => (l ? '  ' + l : l)).join('\n');
const out = [
  '// GENERATED by tools/build.mjs from apps-script/Code.gs — do not edit; change Code.gs and rebuild.',
  'export function createApp(G, HOOKS) {',
  '  var ' + SERVICES.map(s => s + ' = G.' + s).join(', ') + ';',
  indent(code.replace(/\s+$/, '')),
  '  if (HOOKS) {',
  ...HOOKS.map(h => '    if (HOOKS.' + h + ') ' + h + ' = HOOKS.' + h + ';'),
  '  }',
  '  return {',
  names.map(n => '    get ' + n + '() { return ' + n + '; }').join(',\n'),
  '  };',
  '}',
  ''].join('\n');
fs.writeFileSync(path.join(cf, 'src', 'app.generated.js'), out);

// website → public/
const pub = path.join(cf, 'public');
fs.rmSync(pub, { recursive: true, force: true });
const copy = (from, to) => {
  if (fs.statSync(from).isDirectory()) { fs.mkdirSync(to, { recursive: true }); for (const f of fs.readdirSync(from)) copy(path.join(from, f), path.join(to, f)); }
  else fs.copyFileSync(from, to);
};
fs.mkdirSync(pub, { recursive: true });
for (const f of fs.readdirSync(root)) if (f.endsWith('.html')) copy(path.join(root, f), path.join(pub, f));
for (const d of ['assets', 'samples']) if (fs.existsSync(path.join(root, d))) copy(path.join(root, d), path.join(pub, d));
let cfg = fs.readFileSync(path.join(root, 'config.js'), 'utf8');
cfg = cfg.replace(/^\/\* =+[\s\S]*?=+ \*\/\n/, `/* ===========================================================================
 * KIU CBT — front-end configuration
 * ---------------------------------------------------------------------------
 * Cloudflare version: the website and the examination service share one address, so API_URL is
 * simply "/api". Everything else (duration, recording quality, photo/camera rules…) is set in
 * admin.html → Settings.
 * =========================================================================== */
`).replace(/^(\s*)API_URL:\s*"[^"]*",\n/m, '$1API_URL: "/api",\n$1PLATFORM: "cloudflare",\n');
fs.writeFileSync(path.join(pub, 'config.js'), cfg);
console.log('Built src/app.generated.js and public/ from the shared sources.');
